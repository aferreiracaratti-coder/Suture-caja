CREATE TABLE organizations (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(160) NOT NULL,
 currency VARCHAR(3) NOT NULL DEFAULT 'UYU',
 allow_negative_stock BOOLEAN NOT NULL DEFAULT FALSE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id BIGINT NOT NULL REFERENCES organizations(id),
 username VARCHAR(100) NOT NULL UNIQUE,
 password_hash VARCHAR(100) NOT NULL,
 role VARCHAR(20) NOT NULL CHECK (role IN ('ADMINISTRADOR','SUPERVISOR','CAJERO')),
 enabled BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE categories (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id BIGINT NOT NULL REFERENCES organizations(id),
 name VARCHAR(120) NOT NULL,
 UNIQUE (organization_id, name),
 UNIQUE (organization_id, id)
);
CREATE TABLE products (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id BIGINT NOT NULL REFERENCES organizations(id),
 category_id BIGINT,
 name VARCHAR(180) NOT NULL,
 description TEXT,
 sku VARCHAR(80) NOT NULL,
 barcode VARCHAR(80),
 price NUMERIC(15,2) NOT NULL CHECK (price >= 0),
 cost NUMERIC(15,2) NOT NULL DEFAULT 0 CHECK (cost >= 0),
 unit VARCHAR(20) NOT NULL DEFAULT 'UNIT',
 quantity_scale SMALLINT NOT NULL DEFAULT 0 CHECK (quantity_scale BETWEEN 0 AND 3),
 active BOOLEAN NOT NULL DEFAULT TRUE,
 stock NUMERIC(15,3) NOT NULL DEFAULT 0,
 minimum_stock NUMERIC(15,3) NOT NULL DEFAULT 0,
 image_url TEXT,
 version BIGINT NOT NULL DEFAULT 0,
 UNIQUE (organization_id, sku),
 UNIQUE (organization_id, id),
 FOREIGN KEY (organization_id, category_id) REFERENCES categories(organization_id,id)
);
CREATE UNIQUE INDEX ux_products_barcode ON products(organization_id,barcode) WHERE barcode IS NOT NULL;
CREATE INDEX ix_products_name ON products(organization_id,LOWER(name));
CREATE TABLE registers (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id BIGINT NOT NULL REFERENCES organizations(id),
 name VARCHAR(100) NOT NULL,
 active BOOLEAN NOT NULL DEFAULT TRUE,
 UNIQUE (organization_id,name),
 UNIQUE (organization_id,id)
);
CREATE TABLE shifts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id BIGINT NOT NULL REFERENCES organizations(id),
 register_id BIGINT NOT NULL,
 opened_by BIGINT NOT NULL REFERENCES users(id),
 closed_by BIGINT REFERENCES users(id),
 opened_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 closed_at TIMESTAMPTZ,
 status VARCHAR(10) NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','CLOSED')),
 opening_amount NUMERIC(15,2) NOT NULL CHECK (opening_amount >= 0),
 counted_amount NUMERIC(15,2),
 expected_amount NUMERIC(15,2),
 difference_amount NUMERIC(15,2),
 notes TEXT,
 close_reason TEXT,
 UNIQUE (organization_id,id),
 FOREIGN KEY (organization_id,register_id) REFERENCES registers(organization_id,id)
);
CREATE UNIQUE INDEX ux_shifts_open_register ON shifts(register_id) WHERE status='OPEN';
CREATE INDEX ix_shifts_org_opened ON shifts(organization_id,opened_at DESC);
CREATE TABLE sales (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id BIGINT NOT NULL REFERENCES organizations(id),
 shift_id BIGINT NOT NULL,
 cashier_id BIGINT NOT NULL REFERENCES users(id),
 idempotency_key UUID NOT NULL,
 status VARCHAR(12) NOT NULL CHECK (status IN ('PAID','CANCELLED')),
 subtotal NUMERIC(15,2) NOT NULL,
 line_discount NUMERIC(15,2) NOT NULL DEFAULT 0,
 discount NUMERIC(15,2) NOT NULL DEFAULT 0,
 total NUMERIC(15,2) NOT NULL,
 change_amount NUMERIC(15,2) NOT NULL DEFAULT 0,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 cancelled_at TIMESTAMPTZ,
 cancelled_by BIGINT REFERENCES users(id),
 cancel_reason TEXT,
 fiscal_document_id VARCHAR(120),
 UNIQUE (organization_id,idempotency_key),
 UNIQUE (organization_id,id),
 FOREIGN KEY (organization_id,shift_id) REFERENCES shifts(organization_id,id)
);
CREATE INDEX ix_sales_org_date ON sales(organization_id,created_at DESC);
CREATE INDEX ix_sales_shift ON sales(organization_id,shift_id);
CREATE TABLE sale_items (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id BIGINT NOT NULL,
 sale_id BIGINT NOT NULL,
 product_id BIGINT NOT NULL,
 product_name VARCHAR(180) NOT NULL,
 sku VARCHAR(80) NOT NULL,
 quantity NUMERIC(15,3) NOT NULL CHECK (quantity > 0),
 unit_price NUMERIC(15,2) NOT NULL,
 unit_cost NUMERIC(15,2) NOT NULL,
 discount NUMERIC(15,2) NOT NULL DEFAULT 0,
 total NUMERIC(15,2) NOT NULL,
 FOREIGN KEY (organization_id,sale_id) REFERENCES sales(organization_id,id),
 FOREIGN KEY (organization_id,product_id) REFERENCES products(organization_id,id)
);
CREATE TABLE payments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id BIGINT NOT NULL,
 sale_id BIGINT NOT NULL,
 method VARCHAR(20) NOT NULL CHECK (method IN ('CASH','DEBIT_CARD','CREDIT_CARD','TRANSFER','OTHER')),
 amount NUMERIC(15,2) NOT NULL CHECK (amount > 0),
 tendered NUMERIC(15,2),
 change_amount NUMERIC(15,2) NOT NULL DEFAULT 0,
 external_status VARCHAR(20) NOT NULL DEFAULT 'DECLARED',
 FOREIGN KEY (organization_id,sale_id) REFERENCES sales(organization_id,id)
);
CREATE TABLE cash_movements (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id BIGINT NOT NULL,
 shift_id BIGINT NOT NULL,
 actor_id BIGINT NOT NULL REFERENCES users(id),
 sale_id BIGINT,
 type VARCHAR(20) NOT NULL CHECK (type IN ('SALE_CASH','IN','OUT','CANCEL_CASH')),
 amount NUMERIC(15,2) NOT NULL CHECK (amount <> 0),
 reason TEXT NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (organization_id,shift_id) REFERENCES shifts(organization_id,id),
 FOREIGN KEY (organization_id,sale_id) REFERENCES sales(organization_id,id)
);
CREATE INDEX ix_cash_movements_shift ON cash_movements(organization_id,shift_id,created_at);
CREATE TABLE stock_movements (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id BIGINT NOT NULL,
 product_id BIGINT NOT NULL,
 sale_id BIGINT,
 actor_id BIGINT NOT NULL REFERENCES users(id),
 type VARCHAR(20) NOT NULL CHECK (type IN ('INITIAL','IN','OUT','ADJUST','SALE','CANCEL_SALE')),
 quantity NUMERIC(15,3) NOT NULL CHECK (quantity <> 0),
 balance_after NUMERIC(15,3) NOT NULL,
 reason TEXT NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (organization_id,product_id) REFERENCES products(organization_id,id),
 FOREIGN KEY (organization_id,sale_id) REFERENCES sales(organization_id,id)
);
CREATE INDEX ix_stock_movements_product ON stock_movements(organization_id,product_id,created_at DESC);
CREATE TABLE audit_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id BIGINT NOT NULL REFERENCES organizations(id),
 actor_id BIGINT NOT NULL REFERENCES users(id),
 action VARCHAR(60) NOT NULL,
 entity_type VARCHAR(40) NOT NULL,
 entity_id BIGINT NOT NULL,
 detail TEXT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_audit_org_date ON audit_events(organization_id,created_at DESC);
CREATE TABLE print_jobs (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id BIGINT NOT NULL REFERENCES organizations(id),
 sale_id BIGINT NOT NULL,
 job_id VARCHAR(160) NOT NULL UNIQUE,
 status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
 attempts INT NOT NULL DEFAULT 0,
 last_error TEXT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (organization_id,sale_id) REFERENCES sales(organization_id,id)
);
